  // COLOUR WHEEL CLICK
  // ========================================

  colourWheel.addEventListener("click", function(event) {

    if (currentColours.length === 0) {
      return;
    }

    let rect = colourWheel.getBoundingClientRect();

    let x = event.clientX - rect.left - rect.width / 2;
    let y = event.clientY - rect.top - rect.height / 2;

    let angle = Math.atan2(y, x) * (180 / Math.PI);

    angle = angle + 90;

    if (angle < 0) {
      angle = angle + 360;
    }

    let sliceSize = 360 / currentColours.length;

    let slice = Math.floor(angle / sliceSize);

    let selectedColour = currentColours[slice];

    colourName.textContent = selectedColour.name;
    colourName.style.color = selectedColour.colour;

  });


